#!/usr/bin/env python3
"""Generate the CV's "Talks and conferences" LaTeX list from the shared data.

    _data/talks.yml   (canonical)
        └── scripts/talks.py --tex ─▶ a LaTeX itemize for the CV

Most entries are structured (year, date, title, venue); a few heterogeneous
ones keep the CV line verbatim in `text`. Fields may contain LaTeX (math in
titles, \\href in venues), so they are emitted verbatim — not escaped.

An optional `slides` URL renders as a trailing ", \\href{url}{slides}." on the
CV line. The website /slides/ page uses further optional fields (video,
web_title, note) that the CV ignores.

    python3 scripts/talks.py --tex cv/sections/talks_generated.tex
    add --check to compare against an existing file instead of writing.
"""
import argparse
import os
import sys

import yaml

DATA = '_data/talks.yml'
HEADER = '% GENERATED by scripts/talks.py from ' + DATA + ' -- do not edit.\n'


def reconstruct(e):
    if 'title' not in e:
        return e['text']
    line = f"{e['year']}, {e['date']}, {{\\emph{{{e['title']}}}}}, {e['venue']}"
    if e.get('slides'):
        line += f", \\href{{{e['slides']}}}{{slides}}."
    return line


def to_tex(entries):
    items = '\n'.join('\\item\n' + reconstruct(e) for e in entries)
    return HEADER + '\\begin{itemize}\n' + items + '\n\\end{itemize}\n'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--tex', default='-')
    ap.add_argument('--check', action='store_true')
    a = ap.parse_args()
    entries = yaml.safe_load(open(DATA, encoding='utf-8'))
    out = to_tex(entries)

    if a.check:
        cur = open(a.tex, encoding='utf-8').read() if os.path.exists(a.tex) else None
        if cur == out:
            print(f'OK: {a.tex} is up to date with {DATA}')
            return 0
        sys.stderr.write(f'ERROR: {a.tex} is stale; regenerate with '
                         f'scripts/talks.py --tex {a.tex}\n')
        return 1

    if a.tex == '-':
        sys.stdout.write(out)
    else:
        with open(a.tex, 'w', encoding='utf-8') as fh:
            fh.write(out)
        print(f'Wrote {a.tex} ({len(entries)} talks)')
    return 0


if __name__ == '__main__':
    sys.exit(main())
